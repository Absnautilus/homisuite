-- Turni / Shift Planner foundation.
--
-- This migration is deliberately additive: it creates the canonical,
-- property-scoped data model and its authorization boundary without moving
-- any data from the legacy Plannerturni project and without enabling the
-- module for any property. Module entitlement remains an explicit later
-- release step.

-- ---------------------------------------------------------------------------
-- Permissions
-- ---------------------------------------------------------------------------

insert into permissions (slug, module_id)
select permission_slug, m.id
from modules m
cross join (values
  ('shifts.view'),
  ('shifts.manage'),
  ('shifts.requests.manage')
) as wanted(permission_slug)
where m.slug = 'shifts'
on conflict (slug) do update set module_id = excluded.module_id;

insert into role_permissions (role_id, permission_id)
select r.id, p.id
from roles r
join (values
  ('organization_admin', 'shifts.view'),
  ('organization_admin', 'shifts.manage'),
  ('organization_admin', 'shifts.requests.manage'),
  ('property_admin', 'shifts.view'),
  ('property_admin', 'shifts.manage'),
  ('property_admin', 'shifts.requests.manage'),
  ('manager', 'shifts.view'),
  ('manager', 'shifts.manage'),
  ('manager', 'shifts.requests.manage'),
  ('receptionist', 'shifts.view')
) as wanted(role_slug, permission_slug) on wanted.role_slug = r.slug
join permissions p on p.slug = wanted.permission_slug
on conflict (role_id, permission_id) do nothing;

