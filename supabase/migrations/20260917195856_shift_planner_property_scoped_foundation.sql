create table shift_staff_profiles (
  id uuid primary key default gen_random_uuid(),
  property_id uuid not null references properties(id) on delete restrict,
  profile_id uuid not null references profiles(id) on delete restrict,
  employee_type text not null default 'day'
    check (employee_type in ('day', 'rotating', 'night', 'director', 'front_office_manager')),
  rest_type text not null default 'rotating'
    check (rest_type in ('rotating', 'fixed')),
  fixed_rest_day smallint check (fixed_rest_day between 0 and 6),
  rotation_slot smallint,
  active boolean not null default true,
  color text,
  extra_shift_codes text[] not null default '{}',
  annual_leave_quota numeric(6,2) not null default 26 check (annual_leave_quota >= 0),
  annual_permission_hours numeric(7,2) not null default 88 check (annual_permission_hours >= 0),
  team_member boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (property_id, profile_id),
  unique (property_id, id),
  check ((rest_type = 'fixed' and fixed_rest_day is not null) or rest_type = 'rotating')
);

create table shifts (
  id bigint generated by default as identity primary key,
  property_id uuid not null references properties(id) on delete restrict,
  staff_profile_id uuid not null,
  shift_date date not null,
  code text not null check (btrim(code) <> ''),
  do_not_move boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (property_id, staff_profile_id, shift_date),
  foreign key (property_id, staff_profile_id)
    references shift_staff_profiles(property_id, id) on delete restrict
);

create table shift_swap_requests (
  id bigint generated by default as identity primary key,
  property_id uuid not null references properties(id) on delete restrict,
  requester_staff_profile_id uuid not null,
  recipient_staff_profile_id uuid not null,
  requester_date date not null,
  recipient_date date not null,
  requester_shift_code text not null check (btrim(requester_shift_code) <> ''),
  recipient_shift_code text not null check (btrim(recipient_shift_code) <> ''),
  status text not null default 'pending'
    check (status in ('pending', 'accepted', 'rejected', 'cancelled')),
  system_note text,
  rejection_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (requester_staff_profile_id <> recipient_staff_profile_id),
  foreign key (property_id, requester_staff_profile_id)
    references shift_staff_profiles(property_id, id) on delete restrict,
  foreign key (property_id, recipient_staff_profile_id)
    references shift_staff_profiles(property_id, id) on delete restrict
);

create table shift_absence_requests (
  id bigint generated by default as identity primary key,
  property_id uuid not null references properties(id) on delete restrict,
  staff_profile_id uuid not null,
  starts_on date not null,
  ends_on date not null,
  absence_type text not null check (absence_type in ('leave', 'permission')),
  affected_shift_code text,
  note text,
  hours numeric(6,2) check (hours is null or hours > 0),
  starts_at time,
  ends_at time,
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected', 'cancelled')),
  rejection_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_on >= starts_on),
  foreign key (property_id, staff_profile_id)
    references shift_staff_profiles(property_id, id) on delete restrict
);

create table shift_preassignment_requests (
  id bigint generated by default as identity primary key,
  property_id uuid not null references properties(id) on delete restrict,
  staff_profile_id uuid not null,
  starts_on date not null,
  ends_on date not null,
  requested_shift_code text not null check (btrim(requested_shift_code) <> ''),
  note text,
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected', 'cancelled')),
  rejection_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_on >= starts_on),
  foreign key (property_id, staff_profile_id)
    references shift_staff_profiles(property_id, id) on delete restrict
);

create table shift_month_states (
  property_id uuid not null references properties(id) on delete restrict,
  month_start date not null check (month_start = date_trunc('month', month_start)::date),
  status text not null default 'draft' check (status in ('draft', 'final')),
  updated_at timestamptz not null default now(),
  primary key (property_id, month_start)
);

create table shift_settings (
  property_id uuid not null references properties(id) on delete restrict,
  key text not null check (btrim(key) <> ''),
