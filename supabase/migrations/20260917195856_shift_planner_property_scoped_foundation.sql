-- Policies use this helper instead of querying shift_staff_profiles under its
-- own RLS. It only answers whether the current Core profile owns the supplied
-- module staff record; it grants no authority by itself.
create function is_shift_staff_self(p_property_id uuid, p_staff_profile_id uuid)
returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1
    from public.shift_staff_profiles s
    where s.property_id = p_property_id
      and s.id = p_staff_profile_id
      and s.profile_id = (select auth.uid())
      and s.active
      and public.has_permission(p_property_id, 'shifts.view')
  );
$$;

revoke all on function is_shift_staff_self(uuid, uuid) from public, anon;
grant execute on function is_shift_staff_self(uuid, uuid) to authenticated;

